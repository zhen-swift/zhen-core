#!/usr/bin/env python3
"""derive-iana-ports.py — generate the `iana` named port set from the IANA registry.

`PORTS-plan.md`'s section on top-N says nmap's frequency table is under the Nmap Public
Source License and is not ours to copy. The resolution taken here is IANA's registry,
which is a public record of assignments.

WHAT THIS CAN AND CANNOT PRODUCE, because the difference decides what the set is called:

  IANA records WHICH ports have an assigned service. It does not record how often
  anything is found open, and it has no ranking of any kind. So this produces a SET,
  not an ordering, and the flag is `iana` rather than `top-100`. Calling a
  registration list `top-100` would be a frequency claim the data cannot support —
  the same mistake `Ports.swift` refuses when it declines to name a service from its
  port number: a guess dressed as a fact.

The set is the well-known range only. Of 1-1023, 682 ports carry a real assignment and
341 are Unassigned or Reserved, so scanning `iana` instead of `1-1023` drops a third of
the probes and loses nothing that was ever going to answer. The registered range above
it adds 5,207 more, which is a different scan and not a default.

Usage:

    ./Scripts/derive-iana-ports.py                 # fetches the registry
    ./Scripts/derive-iana-ports.py path/to.csv     # uses a local copy
"""

import csv
import io
import subprocess
import sys
from pathlib import Path

REGISTRY = ("https://www.iana.org/assignments/service-names-port-numbers/"
            "service-names-port-numbers.csv")
OUT = Path(__file__).resolve().parent.parent / \
    "Sources/ZhenCore/Model/IANAPorts.swift"
WELL_KNOWN_MAX = 1023


def rows(source):
    if source:
        text = Path(source).read_text(encoding="utf-8", errors="replace")
    else:
        # curl rather than urllib: this machine's Python has no certifi bundle wired up
        # and the failure mode is an SSL error that reads like a bug in this script.
        text = subprocess.run(
            ["curl", "-sS", "--max-time", "60", REGISTRY],
            capture_output=True, text=True, check=True).stdout
    return list(csv.DictReader(io.StringIO(text)))


def assigned_well_known(records):
    """Ports 1-1023 with a real service assignment, TCP."""
    ports = {}
    for row in records:
        if (row.get("Transport Protocol") or "").strip() != "tcp":
            continue
        number = (row.get("Port Number") or "").strip()
        if not number.isdigit():
            continue
        value = int(number)
        if not 1 <= value <= WELL_KNOWN_MAX:
            continue
        name = (row.get("Service Name") or "").strip()
        description = (row.get("Description") or "").strip().lower()
        # An entry with no service name, or one explicitly Unassigned or Reserved, is a
        # hole in the registry rather than an assignment. Including them would make this
        # set `1-1023` with extra steps.
        if not name or description in ("reserved", "unassigned"):
            continue
        ports.setdefault(value, name)
    return dict(sorted(ports.items()))


def emit_names(ports):
    """service name -> port, for `zhen ports HOST ssh`.

    One name wins per port and one port per name: the registry has aliases and a few
    names appearing on several ports, and a selector that expanded to three ports
    because the registry lists three would scan things nobody asked for. Lowest port
    wins, which is the well-known one in every case that matters.
    """
    by_name = {}
    for port, name in sorted(ports.items()):
        key = name.lower()
        if key not in by_name:
            by_name[key] = port
    return by_name


def emit(ports):
    body = []
    line = "        "
    for port in sorted(ports):
        piece = f"{port}, "
        if len(line) + len(piece) > 92:
            body.append(line.rstrip())
            line = "        "
        line += piece
    body.append(line.rstrip().rstrip(","))
    numbers = "\n".join(body)
    names = emit_names(ports)
    name_lines = []
    for name in sorted(names):
        name_lines.append(f'        "{name}": {names[name]},')
    name_body = "\n".join(name_lines)
    return f'''// IANAPorts.swift — GENERATED by Scripts/derive-iana-ports.py. Do not edit by hand.
//
// The {len(ports)} ports in 1-{WELL_KNOWN_MAX} that carry a real service assignment in IANA's
// registry, TCP. The other {WELL_KNOWN_MAX - len(ports)} are Unassigned or Reserved.
//
// **A SET, not an ordering, and the name says which.** IANA records which ports have an
// assignment; it does not record how often anything is found open and publishes no
// ranking. So this is `iana` and not `top-100` — calling a registration list `top-100`
// would be a frequency claim the source cannot support, which is the mistake
// `Ports.swift` refuses when it declines to name a service from its port number.
//
// Regenerate rather than edit:
//
//     ./Scripts/derive-iana-ports.py

import Foundation

extension PortSpec {{
    /// Well-known ports with an IANA service assignment. See the file header.
    public static let ianaWellKnown: [UInt16] = [
{numbers}
    ]

    /// Service name to port, for selecting a target by name.
    ///
    /// **This selects; it never names a result.** `Ports.swift` refuses port-to-service
    /// — "something answered on 22, therefore SSH" — which is a claim about what is
    /// running, made from a number, with no evidence. This is the opposite direction and
    /// makes no claim at all: `ssh` is a way of spelling 22 in the REQUEST. What comes
    /// back is still whatever the banner actually said, or nothing.
    ///
    /// One name per port and one port per name. The registry has aliases and a few names
    /// on several ports; a selector that expanded to three because the registry listed
    /// three would scan what nobody asked for. Lowest port wins.
    public static let ianaServiceNames: [String: UInt16] = [
{name_body}
    ]
}}
'''


def main():
    records = rows(sys.argv[1] if len(sys.argv) > 1 else None)
    ports = assigned_well_known(records)
    if not 400 <= len(ports) <= 900:
        sys.exit(f"derive-iana-ports: {len(ports)} assignments is implausible; "
                 "the registry's columns have probably changed.")
    OUT.write_text(emit(ports))
    print(f"wrote {OUT.relative_to(Path.cwd())}: {len(ports)} ports "
          f"of {WELL_KNOWN_MAX} in the well-known range")


if __name__ == "__main__":
    main()
