// plugin.swift — stamps the `zhen` binary with the commit it was built from.
//
// `zhen --version` and `run.tool.commit` read it. Study 2 freezes one build and cites it
// for weeks, and a version string names a release, not a binary.
//
// ── Why a build plugin and not the manifest ──────────────────────────────────────
//
// `Context.gitInformation` in Package.swift is the obvious route, and it goes stale: the
// manifest is evaluated once and cached until Package.swift itself changes, so a build
// after a commit embeds the commit before it. Measured on a scratch package before this
// was written — two commits, two builds, the same hash twice. A stale commit is worse
// than none: it names the wrong code with confidence.
//
// This command reruns whenever git's record of HEAD moves (`.git/logs/HEAD`), the index
// changes, or any source file in the package changes — so the hash follows commits and
// checkouts, and `-dirty` follows edits to tracked files. It only reads: `git` is run with
// `GIT_OPTIONAL_LOCKS=0`, so `status` does not refresh the index, which the build
// sandbox would refuse. With no `.git` (a source archive) or no git, the stamp is nil
// and the binary says "commit unknown" rather than guessing.

import Foundation
import PackagePlugin

@main
struct StampCommit: BuildToolPlugin {
    func createBuildCommands(context: PluginContext, target: Target) throws -> [Command] {
        let root = context.package.directoryURL
        let output = context.pluginWorkDirectoryURL.appending(path: "BuildCommit.swift")
        let git = root.appending(path: ".git")
        var inputs = ["HEAD", "logs/HEAD", "index"]
            .map { git.appending(path: $0) }
            .filter { FileManager.default.fileExists(atPath: $0.path) }
        for case let module as SourceModuleTarget in context.package.targets {
            inputs += module.sourceFiles.map(\.url)
        }
        let script = """
            commit=$(GIT_OPTIONAL_LOCKS=0 git -C "$1" rev-parse HEAD 2>/dev/null)
            if [ -n "$commit" ] && [ -n "$(GIT_OPTIONAL_LOCKS=0 git -C "$1" status --porcelain --untracked-files=no 2>/dev/null)" ]; then
              commit="$commit-dirty"
            fi
            if [ -n "$commit" ]; then value="\\"$commit\\""; else value="nil"; fi
            printf '// Generated by the StampCommit plugin. Do not edit.\\nnonisolated enum BuildStamp {\\n    static let commit: String? = %s\\n}\\n' "$value" > "$2"
            """
        return [.buildCommand(
            displayName: "Stamping zhen with its commit",
            executable: URL(fileURLWithPath: "/bin/sh"),
            arguments: ["-c", script, "stamp-commit", root.path, output.path],
            environment: ["PATH": "/usr/bin:/bin:/usr/local/bin:/opt/homebrew/bin"],
            inputFiles: inputs,
            outputFiles: [output]
        )]
    }
}
