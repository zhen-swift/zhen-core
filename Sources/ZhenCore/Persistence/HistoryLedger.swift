// HistoryLedger.swift — what "record a run" MEANS, with nowhere to write it down.
//
// Folding a finished run into history is not a storage problem. It is a set of rules
// about identity and change: which candidate keys are allowed to join a new
// observation to an old one, which differences are worth an event, and which are
// worth an event only on the second run and after. None of that has anything to do
// with where the records live, and all of it is easy to get subtly wrong.
//
// ── Why this is a value type and not a store ─────────────────────────────────────
//
// `HistoryStore` has two conformances: an append-only log, which is where history
// lives, and a session-lifetime store for when there is nowhere to write a file. (A
// SwiftData conformance was the third until 2026-09-11, and was withdrawn for shipping
// nowhere — see `HistoryStore.swift`.) If each one carried its own copy of these rules
// they would be two implementations of history, not one idea stored two ways, and the
// day they disagreed the artifact would not say which was right. The seam was moved
// into core so a second conformance would be cheap; that only holds if the expensive
// part — this — is above both of them. It is also what made removing one cheap.
//
// So the rules live here, in a struct with no I/O, no actor and no platform. A store
// loads a ledger, folds a run into it, writes back what changed, and contributes
// nothing to the meaning of the result. That also makes the rules testable without a
// store at all, which is the shape the anti-collapse guard below deserves: it is the
// one piece of this whose failure is unrecoverable.
//
// ── The working set is a home network, and that decides the shape ────────────────
//
// A store using this loads every record to fold one run. That is deliberate rather
// than conceded. The population is the devices on one network — tens, or low
// hundreds — and at that size loading them costs less than the query machinery that
// would avoid loading them, while the rules stay readable as plain Swift over plain
// collections. A design that indexed for scale here would be paying, in the one place
// where a mistake merges two people's phones, for a network nobody has.

import Foundation

/// How long the event log is kept.
///
/// ── Why this is here and not in a store ─────────────────────────────────────────
///
/// Retention is a rule about what history MEANS — which parts of it stop being worth
/// keeping, and when — and this file is where the rules about that live. A prune
/// written inside a conformance would have to be written again, identically and by
/// hand, the day a second conformance mattered, and the day the two copies disagreed
/// nothing would say which was right. That is the same argument that moved the fold
/// here, and it does not get weaker for a rule that deletes.
///
/// ── Events, and deliberately nothing else ───────────────────────────────────────
///
/// This prunes the event log. It does NOT touch device records, and the Settings line
/// that offers it says "Keep events for" because that is exactly what it does. A pruned
/// device record is a device that comes back as newly discovered — a false alarm,
/// generated by a housekeeping setting, about the one thing this product exists to
/// report accurately. Identity is kept forever and the Settings screen says so beneath
/// the picker.
///
/// ── The default is forever, and the command line takes it ───────────────────────
///
/// The app is the only thing with a retention preference. `zhen` has no such
/// setting and must not acquire a behaviour from one, so every parameter that carries a
/// policy defaults to `.forever` and the CLI passes nothing.
public enum RetentionPolicy: Sendable, Hashable {
    /// Keep every event. The default, and what the command line uses.
    case forever
    /// Keep events younger than this many days.
    case days(Int)

    /// The instant before which events are no longer kept, or nil when they all are.
    ///
    /// Measured from the run being folded rather than from the wall clock. The ledger
    /// has no clock — it is a value type with no I/O, which is what makes these rules
    /// testable without a store — and a rule that read one could only be tested by
    /// waiting for it.
    public func cutoff(before now: Timestamp) -> Timestamp? {
        guard case .days(let days) = self, days > 0 else { return nil }
        return Timestamp(
            millisecondsSinceEpoch: now.millisecondsSinceEpoch - Int64(days) * 86_400_000
        )
    }
}

/// History as a value: every record the session knows, and the rules for folding a
/// new run into them.
///
/// A `HistoryStore` conformance is expected to hold one of these, hand it each report,
/// and persist the difference. It has no notion of where it came from.
public struct HistoryLedger: Sendable {
    /// One device, keyed by the strongest identifier it has presented.
    public struct Record: Sendable, Hashable {
        /// The record as of the most recent run that saw it.
        public var device: Device
        /// The earliest run that saw it — the value `Device(observing:…)` cannot know.
        public var firstSeen: Timestamp
        /// The run that most recently saw it. Compared against the latest run to
        /// decide presence, which is why presence is not stored.
        public var lastRunID: UUID
        /// Every key this device has ever presented, so a device that stops offering
        /// one identifier is still joined by another.
        public var identifiers: Set<HostIdentifier>
        /// Insertion order, so a listing is stable across a reload that does not
        /// preserve dictionary order — which no store does.
        public var ordinal: Int
        /// Every hardware address this device has presented, oldest first, each with
        /// the span it was seen over and how it joined. See `MACSighting` for why this is
        /// here and not on `Device`.
        public var macHistory: [MACSighting]
        /// This device's recent first-contact times, oldest first, at most
        /// `FirstContactSample.retained` of them.
        ///
        /// Here and not on `Device`, by the argument `macHistory` made: a first-contact
        /// time is a fact about one run, the device carries the latest run's, and the
        /// record is where a series of runs is remembered. `ReachPlan` reads the cold
        /// ones to learn how long this network takes to answer when nothing is cached.
        public var firstContactSamples: [FirstContactSample] = []
        /// How many runs in a row expected this device and ended without evidence of it
        /// (F13). Any sighting resets it. Kept with the samples, on the line 0.7.0 carries
        /// through a compaction verbatim.
        public var missStreak: Int = 0

        /// Creates a record. Each field is documented on the property it sets.
        ///
        /// - Parameter macHistory: nil for a record written before 0.7.0, which kept one
        ///   MAC. Its history is seeded from that one, spanning the record's first-seen to
        ///   the device's last-seen — the earliest and latest the ledger can say it was in
        ///   use. A rotation before 0.7.0 was never written down and cannot be recovered;
        ///   for the burned-in MAC most devices have, the seed is simply right.
        public init(
            device: Device, firstSeen: Timestamp, lastRunID: UUID,
            identifiers: Set<HostIdentifier>, ordinal: Int,
            macHistory: [MACSighting]? = nil
        ) {
            self.device = device
            self.firstSeen = firstSeen
            self.lastRunID = lastRunID
            self.identifiers = identifiers
            self.ordinal = ordinal
            self.macHistory = macHistory ?? device.mac.map {
                [MACSighting(mac: $0, firstSeen: firstSeen, lastSeen: device.lastSeen, link: .original)]
            } ?? []
        }

        /// Notes the hardware address an observation carried.
        ///
        /// An address already in the history widens its span — a device that rotates back
        /// is one row, not two. A new one is appended, linked by the identifier the
        /// observation was matched on, which is the thing that did not rotate.
        mutating func observe(_ mac: MACAddress?, at: Timestamp, matchedBy kind: HostIdentifierKind) {
            guard let mac else { return }
            if let index = macHistory.firstIndex(where: { $0.mac == mac }) {
                macHistory[index].firstSeen = min(macHistory[index].firstSeen, at)
                macHistory[index].lastSeen = max(macHistory[index].lastSeen, at)
            } else {
                macHistory.append(MACSighting(
                    mac: mac, firstSeen: at, lastSeen: at,
                    link: macHistory.isEmpty ? .original : .rotation(by: kind)
                ))
            }
        }

        /// Takes in the addresses of a record being absorbed into this one.
        ///
        /// The absorbed record's own first address becomes a merge, by the identifier the
        /// two shared; its rotations stay rotations. An address both records knew is one
        /// row with the wider span, linked however it was linked first.
        mutating func absorb(_ absorbed: [MACSighting], sharing kind: HostIdentifierKind) {
            for var sighting in absorbed {
                if case .original = sighting.link { sighting.link = .merge(by: kind) }
                if let index = macHistory.firstIndex(where: { $0.mac == sighting.mac }) {
                    if sighting.firstSeen < macHistory[index].firstSeen {
                        macHistory[index].link = sighting.link
                    }
                    macHistory[index].firstSeen = min(macHistory[index].firstSeen, sighting.firstSeen)
                    macHistory[index].lastSeen = max(macHistory[index].lastSeen, sighting.lastSeen)
                } else {
                    macHistory.append(sighting)
                }
            }
            macHistory.sort { ($0.firstSeen, $0.mac.raw) < ($1.firstSeen, $1.mac.raw) }
        }

        /// Appends a run's first-contact time, keeping the newest `retained`.
        mutating func observeFirstContact(of device: Device) {
            guard let millis = device.firstContactMillis, let cold = device.firstContactCold else { return }
            firstContactSamples.append(FirstContactSample(millis: millis, cold: cold, at: device.lastSeen))
            firstContactSamples = FirstContactSample.newest(firstContactSamples)
        }

        /// The addresses this device presented before its current one, oldest first.
        public var priorMACs: [MACSighting] {
            macHistory.filter { $0.mac != device.mac }
        }
    }

    /// The records, by their primary key.
    public private(set) var records: [HostIdentifier: Record]
    /// Every event derived so far, in the order derived.
    public private(set) var log: [DerivedEvent]
    /// The most recent run folded in, or nil before the first.
    public private(set) var latestRun: ScanRun?
    /// How long events are kept. Settable, because the preference it comes from is a
    /// picker a person can change while the app is open, and a setting that needed a
    /// relaunch to take effect would be the same defect as one that did nothing.
    public var retention: RetentionPolicy
    /// How recently a record must have been seen at an address for a sighting there
    /// with no MAC to join it, ahead of the lease rule (F10).
    ///
    /// The default expected window, and not `--expected-window`: that flag moves which
    /// addresses a scan waits for, and a study flag must not change which record a
    /// sighting joins.
    public var expectedWindow: Duration = ReachSettings.defaultExpectedWindow

    private var nextOrdinal: Int

    /// An empty ledger.
    public init(retention: RetentionPolicy = .forever) {
        self.records = [:]
        self.log = []
        self.latestRun = nil
        self.retention = retention
        self.nextOrdinal = 0
    }

    /// A ledger restored from somewhere it was written down.
    ///
    /// The ordinal counter resumes above the highest it is given, so records added
    /// after a reload sort after the ones that were reloaded rather than colliding
    /// with them.
    public init(
        records: [HostIdentifier: Record], log: [DerivedEvent], latestRun: ScanRun?,
        retention: RetentionPolicy = .forever
    ) {
        self.records = records
        self.log = log
        self.latestRun = latestRun
        self.retention = retention
        self.nextOrdinal = (records.values.map(\.ordinal).max() ?? -1) + 1
    }

    // ── Reads ────────────────────────────────────────────────────────────────────

    /// Everything seen, present and absent, in insertion order then by address.
    public func devices() -> [StoredDevice] {
        let currentRun = latestRun?.id
        return records.values
            .sorted { $0.ordinal < $1.ordinal }
            .map {
                StoredDevice(
                    device: $0.device, isPresent: $0.lastRunID == currentRun,
                    macHistory: $0.macHistory,
                    firstContactSamples: $0.firstContactSamples,
                    missStreak: $0.missStreak
                )
            }
            .sorted { $0.device.primaryAddress < $1.device.primaryAddress }
    }

    /// The event log, newest first.
    public func events() -> [DerivedEvent] {
        log.sorted { $0.at > $1.at }
    }

    /// First-seen stamps for hosts about to be recorded, by address.
    public func firstSeen(
        for facts: [HostFacts], in network: IPv4Network
    ) -> [IPv4Address: Timestamp] {
        var result: [IPv4Address: Timestamp] = [:]
        for host in facts {
            let candidates = HostIdentifier.candidates(for: host, in: network)
            if let match = resolve(candidates) {
                result[host.ip] = records[match.record]?.firstSeen
            }
        }
        return result
    }

    // ── The fold ─────────────────────────────────────────────────────────────────

    /// What a fold changed.
    ///
    /// Two numbers rather than one because a store has to write them down differently.
    /// Events are an append; a prune is a deletion, and a deletion cannot be expressed
    /// as one — an append-only file still holds the lines for what was dropped. A store
    /// that saw only the events would leave pruned events on disk to be read back on the
    /// next open, which is retention that appears to work until you relaunch.
    public struct Fold: Sendable, Hashable {
        /// What changed, for a person to read.
        public var events: [DerivedEvent]
        /// How many events the retention rule dropped from the log.
        public var prunedEvents: Int
        /// How many records were absorbed into another by reconciliation.
        ///
        /// Here for exactly the reason `prunedEvents` is. A merge REMOVES a record, and
        /// an append-only file cannot express a removal: the loser's `device` line is
        /// still on disk, and a store that appended after merging would read that line
        /// back on the next open and resurrect the duplicate. A store seeing a non-zero
        /// count here has to rewrite rather than append.
        public var mergedRecords: Int
        /// How many records a port fold changed.
        ///
        /// A run always writes, because it moves the latest run. A port scan writes only
        /// when it reached a device history holds, and this is how a store tells the
        /// difference without diffing the ledger.
        public var updatedRecords: Int

        /// Creates a value from its fields.
        public init(
            events: [DerivedEvent], prunedEvents: Int, mergedRecords: Int = 0,
            updatedRecords: Int = 0
        ) {
            self.events = events
            self.prunedEvents = prunedEvents
            self.mergedRecords = mergedRecords
            self.updatedRecords = updatedRecords
        }
    }

    /// Folds a finished run in and returns what changed.
    ///
    /// The returned events are also appended to `log`; a caller persisting the delta
    /// wants the return value, and a caller reading history wants the log.
    @discardableResult
    public mutating func record(_ report: ScanReport) -> [DerivedEvent] {
        fold(report).events
    }

    /// Folds a finished run in and reports everything a store has to write down.
    @discardableResult
    public mutating func fold(_ report: ScanReport) -> Fold {
        let network = report.run.target
        let at = report.run.finishedAt ?? report.run.startedAt
        var previouslyPresent = Set(records.filter { $0.value.lastRunID == latestRun?.id }.keys)
        var seenNow: Set<HostIdentifier> = []
        var events: [DerivedEvent] = []

        for device in report.devices {
            let candidates = HostIdentifier.candidates(for: device, in: network)
            guard let key = candidates.first else { continue }

            if let match = joining(device, candidates, in: network, at: at),
               var record = records[match.record] {
                let existing = match.record
                let wasPresent = record.lastRunID == latestRun?.id
                // F10: a sighting with less than the record fills it in; see `observation`.
                let seen = Self.observation(
                    device, joining: record.device, sameRun: record.lastRunID == report.run.id,
                    in: network
                )
                let ports = Self.portChange(
                    from: record.device.ports, to: seen.ports, holding: seen.addresses
                )
                if record.device.primaryAddress != seen.primaryAddress {
                    events.append(DerivedEvent(
                        at: at, kind: .ipChanged, subject: Self.display(seen),
                        detail: "moved \(record.device.primaryAddress) → \(seen.primaryAddress)", runID: report.run.id
                    ))
                }
                if record.device.displayName != seen.displayName, let now = seen.displayName {
                    events.append(DerivedEvent(
                        at: at, kind: .renamed, subject: now,
                        detail: record.device.displayName.map { "· was \($0)" }
                            ?? "· named by \(device.names.best?.source.label ?? "a scan")",
                        runID: report.run.id
                    ))
                }
                if !wasPresent {
                    events.append(DerivedEvent(
                        at: at, kind: .appeared, subject: Self.display(device),
                        detail: "answered again at \(device.primaryAddress)", runID: report.run.id
                    ))
                }
                events += ports.transitions.map {
                    Self.portEvent($0, device: device, at: at, runID: report.run.id)
                }
                var observed = seen
                observed.ports = ports.ports
                record.device = observed
                record.observe(device.mac, at: device.lastSeen, matchedBy: match.by.kind)
                record.observeFirstContact(of: device)
                record.missStreak = 0
                record.lastRunID = report.run.id
                record.identifiers.formUnion(candidates)
                records[existing] = record
                seenNow.insert(existing)
            } else {
                var record = Record(
                    device: device, firstSeen: device.firstSeen,
                    lastRunID: report.run.id, identifiers: Set(candidates),
                    ordinal: nextOrdinal,
                    macHistory: device.mac.map {
                        [MACSighting(mac: $0, firstSeen: device.lastSeen, lastSeen: device.lastSeen, link: .original)]
                    } ?? []
                )
                record.observeFirstContact(of: device)
                records[key] = record
                nextOrdinal += 1
                seenNow.insert(key)
                // Not an event on the first run ever: everything is new then, and eight
                // "appeared" rows on a first launch is noise rather than history.
                if latestRun != nil {
                    events.append(DerivedEvent(
                        at: at, kind: .appeared, subject: Self.display(device),
                        detail: "joined at \(device.primaryAddress)", runID: report.run.id
                    ))
                }
            }
        }

        // Reconciliation goes HERE and not earlier. This run's candidates are usually
        // the bridge that first proves two records are one — a full scan carrying both
        // an mDNS name and a rotated MAC is what links the record keyed by the old MAC
        // to the one keyed by the new — and that evidence only exists after the loop
        // above has unioned those candidates into the record it matched.
        //
        // `join`, not `reconcile`: the joins are logged below with everything else this
        // run derived. Calling `reconcile` here logged them twice — the same event, same
        // id — which the history file 0.6.0 wrote still shows.
        let joined = join(at: at, runID: report.run.id)
        events.append(contentsOf: joined)

        // Both sets are keyed by records that may no longer exist. A key absorbed into
        // its survivor has to follow it, or the device it named is reported as having
        // disappeared in the same run it was merged — a device vanishing at the exact
        // moment the tool decided it was something it already knew about.
        if !joined.isEmpty {
            seenNow = Set(seenNow.compactMap(surviving))
            previouslyPresent = Set(previouslyPresent.compactMap(surviving))
        }

        // F13: an address the run expected and found nothing at is a miss for the device
        // history holds there. Counted after the sightings, so a v6-only sighting of the
        // device still leaves its v4 address missed.
        for address in report.run.reach?.expectedMissing ?? [] {
            if let key = holder(of: address) { records[key]?.missStreak += 1 }
        }

        for key in previouslyPresent.subtracting(seenNow) {
            guard let record = records[key] else { continue }
            events.append(DerivedEvent(
                at: at, kind: .disappeared, subject: Self.display(record.device),
                detail: "last answered at \(record.device.primaryAddress)", runID: report.run.id
            ))
        }

        latestRun = report.run
        log.append(contentsOf: events)
        // Last, so that a run is folded into the whole log before any of it is dropped,
        // and so the events this run derived are subject to the same rule as the rest.
        return Fold(
            events: events,
            prunedEvents: pruneEvents(asOf: at),
            mergedRecords: joined.count
        )
    }

    // ── Look longer ──────────────────────────────────────────────────────────────

    /// Folds what a look-longer sweep found into the latest run, and nothing else.
    ///
    /// ── Why this is not `fold` either ───────────────────────────────────────────
    ///
    /// For the reason `foldPorts` is not: a run is a claim about what was present, and a
    /// sweep of six addresses folded as a run would mark the rest of the network absent.
    /// Look longer is the same scan carried on for the addresses it was still waiting
    /// for, so what it finds belongs to the run it extends: a found device gets that
    /// run's id, and an `appeared` if the run had not seen it. Nothing else changes —
    /// no other record, no `disappeared`, not the latest run, and no reconciliation,
    /// which can remove a record and is a run's business.
    ///
    /// For a record it does change, the extension updates what the sweep observed — its
    /// addresses, hardware address, TTL, round trip, sources, first contact and
    /// `lastSeen` — and keeps what a sweep cannot see: names, ports, fingerprint, vendor.
    /// A device the run already had is left exactly as it is.
    ///
    /// - Parameters:
    ///   - devices: what the sweep found. Each is matched like a run's device.
    ///   - runID: the run being extended. Anything but the latest run is refused with an
    ///     empty fold: extending an older run would rewrite a past that a later run has
    ///     already superseded.
    /// - Returns: the events, and how many records changed.
    @discardableResult
    public mutating func foldExtension(_ devices: [Device], of runID: UUID) -> Fold {
        guard let run = latestRun, run.id == runID else {
            return Fold(events: [], prunedEvents: 0)
        }
        let network = run.target
        var events: [DerivedEvent] = []
        var updated = 0
        for device in devices {
            let at = device.lastSeen
            let candidates = HostIdentifier.candidates(for: device, in: network)
            guard let key = candidates.first else { continue }
            if let match = resolve(candidates), var record = records[match.record] {
                guard record.lastRunID != runID else { continue }
                var observed = record.device
                // F10: a sighting without the MAC the record has takes no address away.
                if device.mac == nil, record.device.mac != nil {
                    observed.addresses = device.addresses.union(record.device.addresses)
                    observed.addressSources = record.device.addressSources
                        .merging(device.addressSources) { _, new in new }
                } else {
                    observed.addresses = device.addresses
                    observed.addressSources = device.addressSources
                }
                observed.mac = device.mac ?? observed.mac
                observed.ttl = device.ttl ?? observed.ttl
                observed.rtt = device.rtt ?? observed.rtt
                observed.discoveredVia = device.discoveredVia
                observed.lastSeen = device.lastSeen
                observed.firstContactMillis = device.firstContactMillis
                observed.firstContactCold = device.firstContactCold
                record.device = observed
                record.observe(device.mac, at: device.lastSeen, matchedBy: match.by.kind)
                record.observeFirstContact(of: device)
                record.missStreak = 0
                record.lastRunID = runID
                record.identifiers.formUnion(candidates)
                records[match.record] = record
                events.append(DerivedEvent(
                    at: at, kind: .appeared, subject: Self.display(observed),
                    detail: "answered again at \(device.primaryAddress)", runID: runID
                ))
            } else {
                var record = Record(
                    device: device, firstSeen: device.firstSeen,
                    lastRunID: runID, identifiers: Set(candidates),
                    ordinal: nextOrdinal,
                    macHistory: device.mac.map {
                        [MACSighting(mac: $0, firstSeen: device.lastSeen, lastSeen: device.lastSeen, link: .original)]
                    } ?? []
                )
                record.observeFirstContact(of: device)
                records[key] = record
                nextOrdinal += 1
                events.append(DerivedEvent(
                    at: at, kind: .appeared, subject: Self.display(device),
                    detail: "joined at \(device.primaryAddress)", runID: runID
                ))
            }
            updated += 1
        }
        log.append(contentsOf: events)
        let at = devices.map(\.lastSeen).max() ?? run.finishedAt ?? run.startedAt
        return Fold(events: events, prunedEvents: pruneEvents(asOf: at), updatedRecords: updated)
    }

    // ── Ports ────────────────────────────────────────────────────────────────────

    /// Folds a port scan in and reports everything a store has to write down.
    ///
    /// ── Why this is not `fold` with a smaller network ───────────────────────────
    ///
    /// Because a port scan is not a run. `fold` takes the run it is given as the latest,
    /// and presence is "seen by the latest run", so a run of one address folded there
    /// marks everything else on the network as gone and derives a `disappeared` for each
    /// of them. That is what the app ran into, and why it threw its port results away.
    /// Teaching presence to be scope-aware was considered and declined: a port scan was
    /// already not a run in the command line — `zhen ports` writes nothing — and what was
    /// missing was a way to keep one, not a new meaning for presence.
    ///
    /// So this changes ports, the fingerprint the port probe elicited, and nothing else:
    /// not `lastRunID`, not `latestRun`, not `lastSeen`, not presence. A host that answered
    /// but that no record holds is skipped, because a port answer is not a discovery.
    ///
    /// ── Which record an address belongs to ──────────────────────────────────────
    ///
    /// The one the latest run saw there. An absent record's address is not trusted with
    /// what answers at it now: a lease moves, and the thing answering on 22 at a phone's
    /// old address is somebody else's laptop. Without a hardware address in a port answer
    /// there is no way to tell, so the absent record is left alone rather than given ports
    /// that may not be its own. The app guarded the same case with a MAC comparison; core
    /// has no MAC to compare and so refuses the match instead.
    ///
    /// - Parameters:
    ///   - result: what the port engines observed, by host.
    ///   - targets: the addresses the scan was asked about. A host outside them is not
    ///     folded, whatever the engine handed back.
    ///   - at: when the scan finished, stamped on the events.
    /// - Returns: the events, and a count of records changed so a store knows whether
    ///   there is anything to write.
    @discardableResult
    public mutating func foldPorts(
        _ result: PortScanResult, targeted targets: [IPAddress], at: Timestamp
    ) -> Fold {
        let asked = Set(targets)
        // The events need a run id and there is no run. A fresh one names this scan, and
        // matches no `ScanRun` on purpose: a reader looking for "the run that did this"
        // should find that there was none.
        let scanID = UUID()
        var events: [DerivedEvent] = []
        var updated = 0

        for (address, observations) in result.ports.sorted(by: { $0.key < $1.key })
        where asked.contains(address) {
            guard let key = presentHolder(of: address), var record = records[key] else { continue }
            // An engine leaves `address` nil because it knows its target; history does not.
            let stamped = observations.map { observation in
                var stamped = observation
                if stamped.address == nil { stamped.address = address }
                return stamped
            }
            let change = Self.portChange(
                from: record.device.ports, to: stamped, holding: record.device.addresses
            )
            record.device.ports = change.ports
            if let v4 = address.v4, let fingerprint = result.fingerprints[v4] {
                record.device.osFingerprint = fingerprint
            }
            records[key] = record
            updated += 1
            events += change.transitions.map {
                Self.portEvent($0, device: record.device, at: at, runID: scanID)
            }
        }

        log.append(contentsOf: events)
        return Fold(events: events, prunedEvents: pruneEvents(asOf: at), updatedRecords: updated)
    }

    /// The record whose device holds this address, seen most recently: the one a plan
    /// expects there (`ReachPlan.make` takes the device seen last at an address).
    private func holder(of address: IPv4Address) -> HostIdentifier? {
        records
            .filter { $0.value.device.ipv4Addresses.contains(address) }
            .min {
                ($1.value.device.lastSeen, $0.value.ordinal, $0.key)
                    < ($0.value.device.lastSeen, $1.value.ordinal, $1.key)
            }?
            .key
    }

    /// The record the latest run saw at this address, or nil.
    private func presentHolder(of address: IPAddress) -> HostIdentifier? {
        guard let current = latestRun?.id else { return nil }
        return records
            .filter { $0.value.lastRunID == current && $0.value.device.addresses.contains(address) }
            .min { ($0.value.ordinal, $0.key) < ($1.value.ordinal, $1.key) }?
            .key
    }

    /// One port's change of state: the observation history had, and the one that replaced it.
    struct PortTransition: Sendable, Hashable {
        var before: PortObservation
        var after: PortObservation
    }

    /// What a device's ports become when new observations arrive, and which of the
    /// changes are events.
    ///
    /// ── A merge, not a replacement ──────────────────────────────────────────────
    ///
    /// An observation replaces the one for the same port, protocol and address. A port
    /// the new observations do not mention keeps its last known state, because it was
    /// not asked about — and a port that was not asked about has not closed. Replacing
    /// the list wholesale was what `fold` did before ports were events, and it was
    /// harmless then; with events it would make every run without a port stage forget
    /// the ports, and the next run with one report them all as opening.
    ///
    /// The exception is an address the device no longer holds. A port observed at an
    /// address the device has left is a fact about that address, not about the device,
    /// so it is dropped — silently, since leaving an address is already the `ipChanged`.
    ///
    /// ── Which changes are events ────────────────────────────────────────────────
    ///
    /// Only those involving `open`, and only between two observations. See
    /// `DerivedEvent.Kind.portOpened` for why the other twelve pairs are not events and
    /// why a first observation is not one either.
    static func portChange(
        from stored: [PortObservation], to incoming: [PortObservation],
        holding addresses: Set<IPAddress>
    ) -> (ports: [PortObservation], transitions: [PortTransition]) {
        struct Key: Hashable {
            var port: UInt16
            var proto: TransportProtocol
            var address: IPAddress?
            init(_ observation: PortObservation) {
                port = observation.port
                proto = observation.proto
                address = observation.address
            }
        }
        var merged: [Key: PortObservation] = [:]
        // A stored port with no address predates schema 3 and is kept: it cannot be
        // shown to belong to an address the device has left.
        for observation in stored where observation.address.map(addresses.contains) ?? true {
            merged[Key(observation)] = observation
        }
        var transitions: [PortTransition] = []
        for observation in incoming {
            let key = Key(observation)
            if let before = merged[key], (before.state == .open) != (observation.state == .open) {
                transitions.append(PortTransition(before: before, after: observation))
            }
            merged[key] = observation
        }
        return (
            merged.values.sorted(by: PortObservation.canonicalOrder),
            transitions.sorted { PortObservation.canonicalOrder($0.after, $1.after) }
        )
    }

    /// "22/tcp open at 10.10.20.5 · was filtered" — the port, what it is now, where, and
    /// what it was, in the shape the other events' sentences already have.
    private static func portEvent(
        _ transition: PortTransition, device: Device, at: Timestamp, runID: UUID
    ) -> DerivedEvent {
        let after = transition.after
        let place = after.address.map { " at \($0)" } ?? ""
        return DerivedEvent(
            at: at, kind: after.state == .open ? .portOpened : .portClosed,
            subject: display(device),
            detail: "\(after.port)/\(after.proto.rawValue) \(spoken(after.state))\(place)"
                + " · was \(spoken(transition.before.state))",
            runID: runID
        )
    }

    /// A port state as a sentence says it. `open_filtered` is the one whose raw value is
    /// not a phrase.
    private static func spoken(_ state: PortState) -> String {
        switch state {
        case .open: "open"
        case .closed: "closed"
        case .filtered: "filtered"
        case .openFiltered: "open or filtered"
        }
    }

    // ── Reconciliation ───────────────────────────────────────────────────────────

    /// Joins records that are provably the same device.
    ///
    /// ── The property this makes true ────────────────────────────────────────────
    ///
    /// `resolve` below has always claimed that "a missed merge is recoverable, since the
    /// next observation carrying a shared key joins the two records". It did not join
    /// them. `fold` resolves an incoming observation to ONE record and leaves any other
    /// record carrying the same key standing, and `match` then hands every later
    /// observation to whichever of them is KEYED by the candidate. The result is a
    /// device that oscillates between two rows depending on which keys a given scan
    /// happened to produce — a full scan with an mDNS name resolving to one, a
    /// discovery-only scan with nothing but a MAC resolving to the other.
    ///
    /// That is what this repairs, and the comment above `resolve` is now accurate.
    ///
    /// ── What counts as proof, and why not more ──────────────────────────────────
    ///
    /// A shared identifier of any kind EXCEPT `ipLease`. That is not a new rule: those
    /// are precisely the keys `resolve` already joins observations on, so if two devices
    /// could collide on one, observations are already being handed to the wrong record.
    /// Merging makes the existing rule consistent rather than adding a looser one.
    ///
    /// `ipLease` stays out, and it is the whole of the caution. Two devices that held
    /// one address at different times both carry that lease key forever; merging on it
    /// would fuse a burned-in `universalMAC` device with a randomized-MAC one on the
    /// evidence that they once shared a DHCP offer. That is the collapse the two-pass
    /// guard in `resolve` exists to prevent, and it is unaffected by this.
    ///
    /// ── Which record survives ───────────────────────────────────────────────────
    ///
    /// The lowest `ordinal`, which is the rule `match` already states and for the reason
    /// it gives: every record minted later has a higher ordinal, so a device joining the
    /// network can never change how an existing one resolves. The survivor keeps its key
    /// and its ordinal, takes the earlier `firstSeen`, the union of the identifiers, and
    /// the observation from whichever record was seen most recently.
    ///
    /// - Returns: the events to emit, one per group joined rather than one per pair.
    @discardableResult
    public mutating func reconcile(at: Timestamp, runID: UUID) -> [DerivedEvent] {
        let events = join(at: at, runID: runID)
        log.append(contentsOf: events)
        return events
    }

    /// The joins `reconcile` makes, without logging them, for a caller that logs them
    /// itself — the fold, which logs everything a run derived at once.
    private mutating func join(at: Timestamp, runID: UUID) -> [DerivedEvent] {
        var events: [DerivedEvent] = []

        // Repeated to a fixed point rather than a single pass. Merging A into B can put
        // B in the same group as C — three records chained by two different shared keys
        // are one device, and a single pass would leave the third behind.
        while let (shared, group) = nextGroup() {
            let ordered = group.sorted { lhs, rhs in
                guard let left = records[lhs], let right = records[rhs] else { return lhs < rhs }
                return (left.ordinal, lhs) < (right.ordinal, rhs)
            }
            guard let survivorKey = ordered.first, var survivor = records[survivorKey] else {
                break
            }
            var absorbed = 0
            for key in ordered.dropFirst() {
                guard let loser = records.removeValue(forKey: key) else { continue }
                survivor.identifiers.formUnion(loser.identifiers)
                survivor.identifiers.insert(key)
                survivor.firstSeen = min(survivor.firstSeen, loser.firstSeen)
                survivor.absorb(loser.macHistory, sharing: shared.kind)
                // F10: the newest of the union by time. Putting the loser's first and
                // keeping the last 32 dropped the loser's newest whenever it was the
                // record seen most recently.
                survivor.firstContactSamples = FirstContactSample.newest(
                    loser.firstContactSamples + survivor.firstContactSamples
                )
                // The most recent observation wins the device and the run it came from,
                // so a merge never rolls a device's address or name backwards.
                if loser.device.lastSeen > survivor.device.lastSeen {
                    survivor.device = loser.device
                    survivor.lastRunID = loser.lastRunID
                    // F13: the misses of whichever was seen last.
                    survivor.missStreak = loser.missStreak
                }
                absorbed += 1
            }
            records[survivorKey] = survivor
            guard absorbed > 0 else { break }

            events.append(DerivedEvent(
                at: at, kind: .merged, subject: Self.display(survivor.device),
                detail: "· was tracked as \(Self.spelled(absorbed + 1)) devices",
                runID: runID
            ))
        }
        return events
    }

    /// Small counts as words, which is how the rest of these sentences read.
    ///
    /// A join of more than a handful of records is possible and is not worth a word, so
    /// the numeral takes over where the spelling would start sounding like a count.
    private static func spelled(_ count: Int) -> String {
        switch count {
        case 2: "two"
        case 3: "three"
        case 4: "four"
        case 5: "five"
        default: "\(count)"
        }
    }

    /// The record a key now belongs to, or nil when nothing claims it any more.
    ///
    /// After a merge the loser's key survives inside the winner's identifier set, which
    /// is what lets an observation carrying the old key still find the device.
    private func surviving(_ key: HostIdentifier) -> HostIdentifier? {
        if records[key] != nil { return key }
        return records
            .filter { $0.value.identifiers.contains(key) }
            .min { ($0.value.ordinal, $0.key) < ($1.value.ordinal, $1.key) }?
            .key
    }

    /// The next set of record keys that share an identifier stronger than a lease.
    ///
    /// Returns nil when nothing is left to join, which is what ends the loop above. The
    /// identifier comes back with the group because it is the reason they joined, and a
    /// MAC history says why each address belongs to the device.
    private func nextGroup() -> (shared: HostIdentifier, keys: Set<HostIdentifier>)? {
        var claimants: [HostIdentifier: Set<HostIdentifier>] = [:]
        for (key, record) in records {
            // The record's own key counts: a record keyed by an identifier another
            // record merely carries is the exact shape of the duplicate this repairs.
            for identifier in record.identifiers.union([key]) where identifier.kind != .ipLease {
                claimants[identifier, default: []].insert(key)
            }
        }
        // Deterministic: the same ledger must reconcile the same way whatever order the
        // dictionary iterated in, for the same reason `match` sorts rather than taking
        // the first hit.
        return claimants
            .filter { $0.value.count > 1 }
            .min { ($0.key, $0.value.count) < ($1.key, $1.value.count) }
            .map { (shared: $0.key, keys: $0.value) }
    }

    /// Drops events older than the retention policy allows, and returns how many.
    ///
    /// **Records are not touched, and that is the rule rather than an oversight.** A
    /// device record is what makes a device that has been quiet for a year the same
    /// device when it answers again; dropping it would make the housekeeping setting
    /// generate the alarm the product exists to raise honestly.
    ///
    /// Not private, because the fold is not the only moment retention has to apply.
    /// It was, and the consequence was retention that only ran when a scan did: a store
    /// opened and read but never written kept returning events the policy said were
    /// gone. `LogHistoryStore` now calls this when it replays the file as well.
    mutating func pruneEvents(asOf now: Timestamp) -> Int {
        guard let cutoff = retention.cutoff(before: now) else { return 0 }
        let before = log.count
        log.removeAll { $0.at < cutoff }
        return before - log.count
    }

    // ── A sighting with less than the record (the fixes brief, F10) ──────────────────
    //
    // Gate T's G5 lost its two 500 ms hosts from the expected set, and it happened
    // here. A run can see a device without its MAC — a reply that arrives before the
    // sweep's own ARP has resolved — and then the cache's link-local entry, which still
    // has the MAC, can't fuse with it and is reported as a v6-only device. Both matched
    // the MAC'd record, and each REPLACED its device: the MAC-less one took the MAC and
    // the link-local away, the v6-only one took the v4 address away. A record with no
    // v4 address in the network is neither expected nor counted by `ReachPlan.make`, so
    // the host was never waited for again, and its samples left the network's count.

    /// The record an observation joins, or nil for a new one.
    ///
    /// `resolve`, except for a sighting with no MAC that would join only by its lease: it
    /// joins the record that holds that address now, with a MAC, seen inside
    /// `expectedWindow` — the device that is there — rather than whichever record the
    /// lease rule picks, which can be an older one keyed by the lease alone.
    private func joining(
        _ device: Device, _ candidates: [HostIdentifier], in network: IPv4Network, at: Timestamp
    ) -> (record: HostIdentifier, by: HostIdentifier)? {
        let resolved = resolve(candidates)
        guard device.mac == nil, resolved.map({ $0.by.kind == .ipLease }) ?? true else { return resolved }
        let cutoff = Timestamp(
            millisecondsSinceEpoch: at.millisecondsSinceEpoch - Int64(expectedWindow.milliseconds.rounded())
        )
        for address in device.ipv4Addresses {
            let holder = records
                .filter {
                    $0.value.device.mac != nil && $0.value.device.lastSeen >= cutoff
                        && $0.value.device.ipv4Addresses.contains(address)
                }
                // The most recently seen, then the stated rule's oldest, then the key.
                .min {
                    ($1.value.device.lastSeen, $0.value.ordinal, $0.key)
                        < ($0.value.device.lastSeen, $1.value.ordinal, $1.key)
                }
            if let holder { return (holder.key, .ipLease(address, in: network)) }
        }
        return resolved
    }

    /// What a record's device becomes when a run observes it.
    ///
    /// A sighting with the MAC and a v4 address is the device as this run saw it, and
    /// replaces the record's — that is how a move becomes an `ipChanged`. A sighting with
    /// less than the record — no MAC where it has one, or no v4 address where it has one
    /// — fills it in and takes nothing away: the addresses are the union, and whatever
    /// the sighting doesn't carry is kept. Facts about the run (first contact, when it
    /// was found) are kept only from this same run: a second sighting of one device in a
    /// run doesn't erase the first one's.
    static func observation(
        _ device: Device, joining stored: Device, sameRun: Bool, in network: IPv4Network
    ) -> Device {
        let lacksMAC = device.mac == nil && stored.mac != nil
        let lacksV4 = device.ipv4Addresses.isEmpty && !stored.ipv4Addresses.isEmpty
        guard lacksMAC || lacksV4 else { return device }
        var seen = device
        seen.addresses.formUnion(stored.addresses)
        seen.addressSources = stored.addressSources.merging(device.addressSources) { _, new in new }
        seen.discoveredVia = Set(device.discoveredVia).union(stored.discoveredVia).canonical
        seen.mac = device.mac ?? stored.mac
        if device.names.isEmpty { seen.names = stored.names }
        seen.vendor = device.vendor ?? stored.vendor
        seen.reverseDNS = device.reverseDNS ?? stored.reverseDNS
        seen.dhcpHostname = device.dhcpHostname ?? stored.dhcpHostname
        seen.ttl = device.ttl ?? stored.ttl
        seen.rtt = device.rtt ?? stored.rtt
        seen.osFingerprint = device.osFingerprint ?? stored.osFingerprint
        seen.vlan = device.vlan ?? stored.vlan
        seen.firstSeen = min(device.firstSeen, stored.firstSeen)
        if stored.identification < device.identification {
            seen.identification = stored.identification
            seen.identificationEvidence = stored.identificationEvidence
        }
        if sameRun, device.firstContactMillis == nil {
            seen.firstContactMillis = stored.firstContactMillis
            seen.firstContactCold = stored.firstContactCold
        }
        if sameRun {
            seen.foundAfterMillis = [device.foundAfterMillis, stored.foundAfterMillis].compactMap(\.self).min()
        }
        seen.identityStability = Stability(strongestOf: HostIdentifier.candidates(for: seen, in: network))
        return seen
    }

    /// First hit wins, strongest identifier first — the spec's resolution rule.
    ///
    /// The anti-collapse guard is the important half: an `ipLease` match is accepted
    /// only when nothing stronger matched, because two devices swapping DHCP leases
    /// would otherwise merge into one. A wrong merge is far worse than a missed one —
    /// a missed merge is recoverable, since the next observation carrying a shared key
    /// joins the two records, and un-merging is not: the histories have already been
    /// written into each other and nothing records which half was whose.
    ///
    /// Returns the candidate that matched as well as the record, because which identifier
    /// carried a device across a MAC rotation is the reason its history gives.
    private func resolve(
        _ candidates: [HostIdentifier]
    ) -> (record: HostIdentifier, by: HostIdentifier)? {
        for candidate in candidates where candidate.kind != .ipLease {
            if let match = match(candidate) { return (match, candidate) }
        }
        for candidate in candidates where candidate.kind == .ipLease {
            if let match = match(candidate) { return (match, candidate) }
        }
        return nil
    }

    /// The one record that presents this identifier, chosen by a stated rule.
    ///
    /// ── Why there is a rule here at all ─────────────────────────────────────────
    ///
    /// This used to be `for (key, record) in records where … { return key }`, over a
    /// Dictionary. If two records ever carry the same identifier — and they can, because
    /// a file is written by two processes and read back by a third, and because nothing
    /// stops a record accumulating a key another record already had — then which one
    /// answered depended on hash order. The same history file could fold the same run two
    /// different ways on two different runs, and a device's history would move between
    /// records for no reason anybody could see. Being deterministic about identity is the
    /// whole job of this function.
    ///
    /// ── The rule, and why this one ──────────────────────────────────────────────
    ///
    /// A record keyed by the candidate wins outright: it is the record that claimed the
    /// identifier as its primary key, which is a stronger statement than carrying it in a
    /// join set. Otherwise the OLDEST record wins — lowest ordinal — with the key
    /// breaking ties so the order is total even for a file that arrives with two records
    /// claiming one ordinal.
    ///
    /// Oldest, because the older record is the one with history behind it: its first-seen
    /// is the earlier one, the events already logged describe it, and joining the new
    /// observation to the newer record would strand all of that. And because it is the
    /// only choice that is STABLE — every record added later has a higher ordinal, so a
    /// device joining the network can never change how an existing device resolves. A
    /// rule that took the newest would give a different answer every time anything new
    /// appeared.
    private func match(_ candidate: HostIdentifier) -> HostIdentifier? {
        if records[candidate] != nil { return candidate }
        return records
            .filter { $0.value.identifiers.contains(candidate) }
            .min { ($0.value.ordinal, $0.key) < ($1.value.ordinal, $1.key) }?
            .key
    }

    private static func display(_ device: Device) -> String {
        device.displayName ?? "Unidentified device"
    }
}
